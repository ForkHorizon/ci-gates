"""One-line file headers: print a path-to-role tree and require a header on new files."""

from __future__ import annotations

import argparse
import ast
import os
import re
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

EXCLUDED_PARTS = {".git", "node_modules", "vendor", "Pods", "build", "dist", "out", "target", "obj", "bin"}
SLASH_FAMILY = {".swift", ".ts", ".tsx", ".js", ".jsx", ".mjs", ".cs", ".java", ".kt", ".kts", ".go"}
SUPPORTED = SLASH_FAMILY | {".py"}
NOISE = re.compile(
    r"copyright|created by|licen[sc]e|all rights reserved|^[\w+.-]+\.\w+$|^(swift-format|eslint|prettier|@ts-)",
    re.IGNORECASE,
)
GENERATED = re.compile(r"code generated|generated by|do not edit|@generated|auto-?generated", re.IGNORECASE)
EXEMPT_NAMES = {"__init__.py", "__main__.py"}


@dataclass(frozen=True)
class RoleOptions:
    mode: str
    git_mode: str
    base: str
    head: str


def role_of(extension: str, text: str) -> str | None:
    """First meaningful line of the file's header comment, or None when there is none."""
    if extension == ".py":
        return _python_role(text)
    if extension in SLASH_FAMILY:
        return _slash_role(text, go=extension == ".go")
    return None


def is_generated(text: str) -> bool:
    return bool(GENERATED.search("\n".join(text.splitlines()[:5])))


def _python_role(text: str) -> str | None:
    try:
        doc = ast.get_docstring(ast.parse(text))
    except (SyntaxError, ValueError):
        return None
    return _first_line(doc.splitlines()) if doc else None


def _slash_role(text: str, *, go: bool) -> str | None:
    comment: list[str] = []
    in_block = False
    for raw in text.splitlines():
        line = raw.strip()
        if in_block:
            comment.append(line.removesuffix("*/").lstrip("* ").strip())
            in_block = not line.endswith("*/")
        elif line.startswith("/*"):
            body = line.removeprefix("/**").removeprefix("/*")
            comment.append(body.removesuffix("*/").strip())
            in_block = not line.endswith("*/")
        elif line.startswith("//"):
            comment.append(line.lstrip("/").strip())
        elif not line or line.startswith("#!") or line in {'"use strict";', "'use strict';"}:
            if comment and go:
                comment = []  # Go: only a comment attached to the package clause counts
            continue
        else:
            break
    return _first_line(comment)


def _first_line(lines: list[str]) -> str | None:
    created = [index for index, line in enumerate(lines) if re.search(r"created by", line, re.IGNORECASE)]
    for line in lines[created[-1] + 1 :] if created else lines:  # drop Xcode's name/project/author block
        cleaned = re.sub(r"</?\w+[^>]*>", "", line).strip()
        if cleaned and not NOISE.search(cleaned):
            return cleaned
    return None


def source_files(root: Path) -> list[Path]:
    found = []
    for directory, names, files in os.walk(root):
        names[:] = sorted(name for name in names if name not in EXCLUDED_PARTS)
        for name in sorted(files):
            path = Path(directory) / name
            if path.suffix.lower() in SUPPORTED and not path.is_symlink():
                found.append(path)
    return found


def tree(root: Path) -> list[tuple[str, str | None]]:
    root = root.resolve()
    rows = []
    for path in source_files(root):
        text = path.read_text(encoding="utf-8", errors="replace")
        if is_generated(text):
            continue
        rows.append((path.relative_to(root).as_posix(), role_of(path.suffix.lower(), text)))
    return rows


def added_files(root: Path, options: RoleOptions) -> set[str]:
    revision = f"{options.base}...{options.head}" if options.git_mode == "committed" else "HEAD"
    names = _git(root, "diff", "--name-only", "-z", "--diff-filter=A", revision, "--").split("\0")
    if options.git_mode == "worktree":
        names += _git(root, "ls-files", "--others", "--exclude-standard", "-z").split("\0")
    return {name for name in names if name}


def missing_roles(root: Path, options: RoleOptions) -> list[str]:
    root = root.resolve()
    new = added_files(root, options) if options.mode == "new" else None
    return [
        path
        for path, role in tree(root)
        if role is None and Path(path).name not in EXEMPT_NAMES and (new is None or path in new)
    ]


def _git(root: Path, *args: str) -> str:
    result = subprocess.run(["git", *args], cwd=root, capture_output=True, text=True, check=False)
    if result.returncode:
        raise RuntimeError(result.stderr.strip() or "git command failed")
    return result.stdout


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, required=True)
    parser.add_argument("--tree", action="store_true", help="print 'path - role' for every source file")
    parser.add_argument("--mode", choices=("new", "all"), default="new")
    parser.add_argument("--git-mode", choices=("worktree", "committed"), default="worktree")
    parser.add_argument("--base", default="HEAD~1")
    parser.add_argument("--head", default="HEAD")
    args = parser.parse_args(argv)
    try:
        if args.tree:
            for path, role in tree(args.root):
                print(f"{path} - {role or '(no header)'}")
            return 0
        missing = missing_roles(args.root, RoleOptions(args.mode, args.git_mode, args.base, args.head))
    except (OSError, RuntimeError) as error:
        print(f"file-roles: {error}", file=sys.stderr)
        return 2
    for path in missing:
        print(f"{path}:1  missing-file-header  new file needs a one-line header comment")
    return int(bool(missing))


if __name__ == "__main__":
    raise SystemExit(main())
