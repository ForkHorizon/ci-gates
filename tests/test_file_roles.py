import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from scripts.file_roles import RoleOptions, is_generated, missing_roles, role_of, tree


def git(root, *args):
    subprocess.run(["git", "-C", str(root), *args], check=True, capture_output=True)


class RoleOfTests(unittest.TestCase):
    def test_python_uses_the_module_docstring_first_line(self):
        self.assertEqual(role_of(".py", '"""Parse manifests.\n\nMore.\n"""\nimport os\n'), "Parse manifests.")
        self.assertIsNone(role_of(".py", "# just a comment\nimport os\n"))

    def test_go_needs_a_comment_attached_to_the_package_clause(self):
        self.assertEqual(
            role_of(".go", "// Package agent talks to the server.\npackage agent\n"),
            "Package agent talks to the server.",
        )
        self.assertIsNone(role_of(".go", "// build tag\n\npackage agent\n"))

    def test_swift_skips_xcode_boilerplate_and_takes_triple_slash(self):
        xcode = "//\n//  Panel.swift\n//  CI Scope\n//\n//  Created by Someone on 1/1/26.\n//\n/// Shows the local check.\nimport SwiftUI\n"
        self.assertEqual(role_of(".swift", xcode), "Shows the local check.")
        self.assertIsNone(role_of(".swift", "import SwiftUI\nstruct A {}\n"))

    def test_typescript_block_comment_and_licence_noise(self):
        self.assertEqual(
            role_of(".ts", "/**\n * Encodes runner pool state.\n */\nexport const a = 1;\n"),
            "Encodes runner pool state.",
        )
        self.assertIsNone(role_of(".ts", "// Copyright 2026 Someone\nexport const a = 1;\n"))

    def test_csharp_summary_tags_are_stripped(self):
        self.assertEqual(
            role_of(".cs", "/// <summary>Drives the spawner.</summary>\nclass A {}\n"), "Drives the spawner."
        )

    def test_unsupported_extension_has_no_role(self):
        self.assertIsNone(role_of(".md", "# Title\n"))

    def test_generated_marker_is_detected_near_the_top(self):
        self.assertTrue(is_generated("// Code generated by protoc. DO NOT EDIT.\npackage x\n"))
        self.assertFalse(is_generated("package x\n"))


class RepositoryTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.root = Path(self.temp.name)
        git(self.root, "init", "-q")
        git(self.root, "config", "user.email", "t@example.com")
        git(self.root, "config", "user.name", "Test")
        (self.root / "old.py").write_text("import os\n")
        (self.root / "node_modules").mkdir()
        (self.root / "node_modules/skip.js").write_text("var a;\n")
        git(self.root, "add", ".")
        git(self.root, "commit", "-qm", "base")

    def tearDown(self):
        self.temp.cleanup()

    def test_tree_lists_sources_and_skips_vendored_and_generated(self):
        (self.root / "gen.go").write_text("// Code generated by x. DO NOT EDIT.\npackage g\n")
        (self.root / "new.py").write_text('"""New module."""\n')
        rows = dict(tree(self.root))
        self.assertEqual(rows, {"new.py": "New module.", "old.py": None})

    def test_new_mode_flags_only_added_files_without_header(self):
        (self.root / "new.py").write_text("x = 1\n")
        (self.root / "__init__.py").write_text("")
        options = RoleOptions("new", "worktree", "HEAD~1", "HEAD")
        self.assertEqual(missing_roles(self.root, options), ["new.py"])
        (self.root / "new.py").write_text('"""Has one."""\n')
        self.assertEqual(missing_roles(self.root, options), [])

    def test_all_mode_includes_existing_files(self):
        options = RoleOptions("all", "worktree", "HEAD~1", "HEAD")
        self.assertEqual(missing_roles(self.root, options), ["old.py"])

    def test_committed_mode_uses_the_diff_between_revisions(self):
        (self.root / "added.py").write_text("x = 1\n")
        git(self.root, "add", ".")
        git(self.root, "commit", "-qm", "add")
        options = RoleOptions("new", "committed", "HEAD~1", "HEAD")
        self.assertEqual(missing_roles(self.root, options), ["added.py"])


if __name__ == "__main__":
    unittest.main()
